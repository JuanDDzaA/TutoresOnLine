import handler from '../netlify/functions/asistente-ia.mjs';
import assert from 'node:assert/strict';
const send = data => new Request('https://test.local/.netlify/functions/asistente-ia', { method:'POST',headers:{'content-type':'application/json'}, body:JSON.stringify(data) });
const q = {pregunta:'¿Cómo despejar 2x+5=17?',materia:'Matemáticas',nivel:'Bachillerato',tipo:'explicar',codigo:'private-demo-code-234',historial:[]};
process.env.GEMINI_API_KEY = 'fake-secret-only-for-test';
process.env.IA_ACCESS_CODE = 'private-demo-code-234';
process.env.GEMINI_MODEL = 'gemini-3.8-flash';
const oldFetch = global.fetch;
let received;
global.fetch = async (url, opts) => {
  received = {url, opts};
  return Response.json({steps:[{type:'model_output',content:[{type:'text',text:'Primero resta 5 y luego divide entre 2. x = 6.'}]}]});
};
let response = await handler(send(q));
assert.equal(response.status,200);
assert.equal((await response.json()).respuesta,'Primero resta 5 y luego divide entre 2. x = 6.');
assert.equal(received.url,'https://generativelanguage.googleapis.com/v1beta/interactions');
assert.equal(received.opts.headers['x-goog-api-key'],'fake-secret-only-for-test');
assert.equal(JSON.parse(received.opts.body).model,'gemini-3.8-flash');
response = await handler(send({...q, codigo:'wrong code'}));
assert.equal(response.status,401);
response = await handler(send({...q, pregunta:'x'}));
assert.equal(response.status,400);
global.fetch=async()=>new Response('rate limit',{status:429});
response=await handler(send(q));
assert.equal(response.status,429);
response=await handler(new Request('https://test.local/',{method:'GET'}));
assert.equal(response.status,405);
global.fetch=oldFetch;
console.log('PASS: response generation, access control, bad input, upstream rate limit, method guard.');
